/** Real schools in a suburb (primary/secondary/combined first, then kinders). */
export function schoolsForSuburb(suburb: string, limit = 6): School[] {
  const target = suburb.trim().toLowerCase();
  const matches = SCHOOLS.filter((s) => s.suburb.toLowerCase() === target);
  const rank = (s: School) => (s.type === 'kindergarten' ? 1 : 0);
  return matches.sort((a, b) => rank(a) - rank(b)).slice(0, limit);
}
